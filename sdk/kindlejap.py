def get_events():
    """
    Read touch events. Returns list of event dicts:
    [{'type': 'touch', 'x': int, 'y': int}]
    """
    events = []
    if _input_fd < 0:
        return events

    # struct input_event: timeval(16 bytes on 32-bit) + type(H) + code(H) + value(i)
    # Total: 24 bytes on 32-bit ARM
    EVENT_SIZE = 24
    try:
        while True:
            data = os.read(_input_fd, EVENT_SIZE * 16)
            if not data:
                break
            offset = 0
            while offset + EVENT_SIZE <= len(data):
                etype = struct.unpack("<H", data[offset + 16:offset + 18])[0]
                ecode = struct.unpack("<H", data[offset + 18:offset + 20])[0]
                evalue = struct.unpack("<i", data[offset + 20:offset + 24])[0]

                if etype == EV_ABS and ecode == ABS_MT_POSITION_X:
                    _set_touch_x(evalue)
                elif etype == EV_ABS and ecode == ABS_MT_POSITION_Y:
                    _set_touch_y(evalue)
                elif etype == EV_KEY and ecode == BTN_TOUCH and evalue == 0:
                    events.append({'type': 'touch', 'x': _get_touch_x(), 'y': _get_touch_y()})

                offset += EVENT_SIZE
    except BlockingIOError:
        pass
    except OSError:
        pass

    return events

def _set_touch_x(val):
    global _touch_x
    _touch_x = val

def _set_touch_y(val):
    global _touch_y
    _touch_y = val

def _get_touch_x():
    return _touch_x

def _get_touch_y():
    return _touch_y

