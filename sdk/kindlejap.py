def init():
    """Initialize the KindleJap SDK. Must be called before any drawing."""
    global _fb_fd, _fb_mem, _fb_size, _input_fd
    global _screen_width, _screen_height

    # Open framebuffer
    _fb_fd = os.open("/dev/fb0", os.O_RDWR)

    # Get screen info via ioctl
    # FBIOGET_VSCREENINFO = 0x4600
    vinfo = bytearray(160)
    fcntl.ioctl(_fb_fd, 0x4600, vinfo)
    _screen_width = struct.unpack("I", vinfo[0:4])[0]
    _screen_height = struct.unpack("I", vinfo[4:8])[0]

    # FBIOGET_FSCREENINFO = 0x4602
    finfo = bytearray(100)
    fcntl.ioctl(_fb_fd, 0x4602, finfo)
    line_length = struct.unpack("I", finfo[24:28])[0]
    smem_len = struct.unpack("I", finfo[40:44])[0]

    _fb_size = smem_len
    _fb_mem = mmap.mmap(_fb_fd, _fb_size, mmap.MAP_SHARED, mmap.PROT_READ | mmap.PROT_WRITE)

    # Open touch input device
    _input_fd = _find_input_device()

    # Handle signals for clean exit
    def _signal_handler(sig, frame):
        global _running
        _running = False
    signal.signal(signal.SIGINT, _signal_handler)
    signal.signal(signal.SIGTERM, _signal_handler)


def shutdown():
    """Clean up resources."""
    global _fb_mem, _fb_fd, _input_fd
    if _fb_mem:
        _fb_mem.close()
        _fb_mem = None
    if _fb_fd >= 0:
        os.close(_fb_fd)
        _fb_fd = -1
    if _input_fd >= 0:
        os.close(_input_fd)
        _input_fd = -1


def _find_input_device():
    """Find the touch input device."""
    for path in sorted(glob.glob("/dev/input/event*")):
        try:
            fd = os.open(path, os.O_RDONLY | os.O_NONBLOCK)
            # EVIOCGNAME = 0x4606
            name = bytearray(256)
            try:
                fcntl.ioctl(fd, 0x4606 + (256 << 16), name)
                name_str = name.split(b'\x00')[0].decode('ascii', errors='ignore').lower()
                if 'touch' in name_str or 'multi' in name_str:
                    return fd
            except:
                pass
            os.close(fd)
        except:
            pass
    return -1

