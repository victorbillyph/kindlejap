def run(draw_fn, touch_fn=None, fps=20):
    """
    Run the app with a simple main loop.

    Args:
        draw_fn: Called every frame to draw. Signature: draw_fn()
        touch_fn: Called on touch events. Signature: touch_fn(x, y)
        fps: Frames per second (default 20)
    """
    global _running, _dirty

    _dirty = True
    interval = 1.0 / fps

    while _running:
        # Process input
        events = get_events()
        for event in events:
            if event['type'] == 'touch' and touch_fn:
                touch_fn(event['x'], event['y'])
                _dirty = True

        # Draw
        if _dirty:
            if draw_fn:
                draw_fn()
            _dirty = False

        time.sleep(interval)

    shutdown()
