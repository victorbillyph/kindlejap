def draw_pixel(x, y, color):
    """Draw a single pixel."""
    if 0 <= x < _screen_width and 0 <= y < _screen_height:
        _fb_mem[y * _screen_width + x] = color

def draw_rect(x, y, w, h, color):
    """Fill a rectangle."""
    for j in range(y, min(y + h, _screen_height)):
        if j < 0:
            continue
        offset = j * _screen_width
        for i in range(x, min(x + w, _screen_width)):
            if i >= 0:
                _fb_mem[offset + i] = color

def draw_rounded_rect(x, y, w, h, r, color):
    """Fill a rectangle with rounded corners."""
    if r > w // 2:
        r = w // 2
    if r > h // 2:
        r = h // 2
    for j in range(y, min(y + h, _screen_height)):
        if j < 0:
            continue
        offset = j * _screen_width
        for i in range(x, min(x + w, _screen_width)):
            if i < 0:
                continue
            dx = 0
            dy = 0
            corner = False
            if i < x + r and j < y + r:
                dx = x + r - i
                dy = y + r - j
                corner = True
            elif i >= x + w - r and j < y + r:
                dx = i - (x + w - r - 1)
                dy = y + r - j
                corner = True
            elif i < x + r and j >= y + h - r:
                dx = x + r - i
                dy = j - (y + h - r - 1)
                corner = True
            elif i >= x + w - r and j >= y + h - r:
                dx = i - (x + w - r - 1)
                dy = j - (y + h - r - 1)
                corner = True
            if corner:
                if dx * dx + dy * dy <= r * r:
                    _fb_mem[offset + i] = color
            else:
                _fb_mem[offset + i] = color

def draw_circle(cx, cy, r, color):
    """Fill a circle."""
    for j in range(cy - r, cy + r + 1):
        if j < 0 or j >= _screen_height:
            continue
        offset = j * _screen_width
        for i in range(cx - r, cx + r + 1):
            if i < 0 or i >= _screen_width:
                continue
            if (i - cx) ** 2 + (j - cy) ** 2 <= r * r:
                _fb_mem[offset + i] = color

def draw_line(x0, y0, x1, y1, color):
    """Draw a line using Bresenham's algorithm."""
    dx = abs(x1 - x0)
    dy = -abs(y1 - y0)
    sx = 1 if x0 < x1 else -1
    sy = 1 if y0 < y1 else -1
    err = dx + dy
    while True:
        draw_pixel(x0, y0, color)
        if x0 == x1 and y0 == y1:
            break
        e2 = 2 * err
        if e2 >= dy:
            err += dy
            x0 += sx
        if e2 <= dx:
            err += dx
            y0 += sy

